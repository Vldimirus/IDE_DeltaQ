QString SDL2CodeGenerator::generateMainFile(const UILayout &layout, const QString &baseName)
{
    QString s;
    QTextStream out(&s);

    out << makeGeneratedLayoutBanner(layout, "SDL2 main source", "main.c");
    out << "#include <stdbool.h>\n";
    out << "#include \"" << baseName << ".h\"\n";
    out << "#include \"" << baseName << "_events.h\"\n\n";

    out << "int main(int argc, char *argv[]) {\n";
    out << "    (void)argc; (void)argv;\n\n";

    const int w = generatedWindowInitialWidth(layout);
    const int h = generatedWindowInitialHeight(layout);
    const int minWidth = generatedWindowMinimumWidth(layout);
    const int minHeight = generatedWindowMinimumHeight(layout);
    const QString title = generatedWindowTitle(layout);
    const bool resizable = uiWindowResizable(layout.window);

    out << "    DQ_UIBackendContext backend;\n";
    out << "    if (!dq_ui_backend_init(&backend, "
        << cStringLiteral(title) << ", "
        << w << ", " << h << ", "
        << minWidth << ", " << minHeight << ", "
        << cBoolLiteral(resizable) << ")) {\n";
    out << "        return 1;\n";
    out << "    }\n\n";

    out << "    UIState ui;\n";
    out << "    ui_init(&ui);\n\n";
    out << "    int window_width = 0;\n";
    out << "    int window_height = 0;\n";
    out << "    dq_ui_backend_window_size(&backend, &window_width, &window_height);\n";
    out << "    ui_apply_layout(&ui, window_width, window_height);\n\n";

    out << "    bool running = true;\n";
    out << "    DQ_UIBackendEvent event;\n";
    out << "    DQ_UIRuntimeEvent runtime_event;\n";
    out << "    Uint32 last_tick = dq_ui_backend_ticks();\n\n";

    out << "    while (running) {\n";
    out << "        while (dq_ui_backend_poll_event(&event)) {\n";
    out << "            if (!dq_ui_backend_translate_event(&event, &runtime_event)) {\n";
    out << "                continue;\n";
    out << "            }\n";
    out << "            if (runtime_event.kind == DQ_UIRuntimeEvent_Quit) {\n";
    out << "                running = false;\n";
    out << "                break;\n";
    out << "            }\n";
    out << "            ui_handle_event(&ui, &runtime_event);\n";
    out << "        }\n\n";
    out << "        Uint32 now = dq_ui_backend_ticks();\n";
    out << "        ui_update(&ui, now - last_tick);\n";
    out << "        last_tick = now;\n\n";
    out << "        dq_ui_backend_window_size(&backend, &window_width, &window_height);\n";
    out << "        ui_apply_layout(&ui, window_width, window_height);\n";
    out << "        dq_ui_backend_begin_frame(&backend);\n";
    out << "        ui_render(&ui, backend.renderer);\n";
    out << "        dq_ui_backend_end_frame(&backend);\n";
    out << "    }\n\n";

    out << "    if (ui.font) TTF_CloseFont(ui.font);\n";
    out << "    dq_ui_backend_shutdown(&backend);\n";
    out << "    return 0;\n";
    out << "}\n";

    return s;
}

